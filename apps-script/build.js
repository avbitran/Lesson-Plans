// Combines the source files into the two files you paste into Apps Script:
//   dist/Code.gs     (the whole app: server code with the pages inside)
//   dist/Index.html  (the pages alone, used by test/harness.js)
// Run with: node build.js
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const src = (...p) => fs.readFileSync(path.join(__dirname, 'src', ...p), 'utf8');
const banner = (what) =>
  `Online Tests — ${what}. Generated by build.js from apps-script/src/; edit those files, not this one.`;

const server = ['Core.js', 'Api.js', 'Store.js', 'Main.js'].map((f) => `// ===== ${f} =====\n${src('server', f).trim()}\n`).join('\n');

const scripts = ['common.js', 'speech.js', 'take.js', 'student.js', 'ai-import.js', 'teacher.js', 'app.js'].map((f) => `// ===== ${f} =====\n${src('client', f).trim()}\n`).join('\n');
if (/<\?|\?>|<\/script/i.test(scripts + src('client', 'style.css'))) {
  throw new Error('Client code contains "<?", "?>" or "</script", which would break the Apps Script template.');
}
const html = src('client', 'index.html')
  .replace('/*STYLE*/', () => src('client', 'style.css').trim())
  .replace('/*SCRIPTS*/', () => scripts)
  .replace('<!DOCTYPE html>', `<!DOCTYPE html>\n<!-- ${banner('pages; already included in Code.gs')} -->`);

// The pages ride along inside Code.gs, so there is only one file to paste.
const code = `// ${banner('the whole app: paste this into Code.gs')}\n\n${server}\n// ===== Index.html (the pages) =====\nconst INDEX_HTML = ${JSON.stringify(html)};\n`;

fs.mkdirSync(path.join(__dirname, 'dist'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'dist', 'Code.gs'), code);
fs.writeFileSync(path.join(__dirname, 'dist', 'Index.html'), html);
fs.copyFileSync(path.join(__dirname, 'src', 'appsscript.json'), path.join(__dirname, 'dist', 'appsscript.json'));
console.log(`dist/Code.gs ${code.length} chars (includes the pages)`);
